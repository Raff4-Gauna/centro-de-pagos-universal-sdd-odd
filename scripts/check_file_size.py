"""Fail when a tracked code file exceeds 400 physical lines (C-14, RN-PLT-08, AC-PLT-13).

Usage (from anywhere inside the repo):
    python scripts/check_file_size.py            # every tracked file (CI, job ``file-size``)
    python scripts/check_file_size.py PATH...    # only these paths, if tracked (pre-commit)

Only files tracked by git are checked (``git ls-files -z``, so non-ASCII paths such as
``Programación-2026`` round-trip untouched). Tests count. Exit codes: 0 ok, 1 oversized files
(each one named on stderr), 2 git/usage error. Stdlib only.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path, PurePosixPath

from glob_paths import match_any

# Hard limit (Q-043): 400 lines pass, 401 fail.
MAX_LINES = 400

# Code files covered by C-14.
CODE_SUFFIXES = frozenset({".py", ".ts", ".tsx", ".jsx"})

# Explicit exclusions (Q-043, context/08 sec. 1). Each entry needs a reason; keep this list short.
EXCLUDED_GLOBS = (
    # Django migrations of the real apps: the `NNNN_*.py` modules makemigrations writes (the same
    # modules ruff.toml waives). Not a helper next to them, nor backend/tests/migrations/ (the
    # migration-check tests and their synthetic apps are hand-written code, T-PLT-22). `?` stands
    # for each digit: glob_paths has no character classes.
    "backend/apps/**/migrations/????_*.py",
    # Fixtures (sanitized provider sandbox payloads): data, not code.
    "**/fixtures/**",
    # Generated from specs/_contracts/openapi.yaml (ADR-0005); never edited by hand.
    "frontend/src/types/**",
    # Generated by Next.js.
    "**/next-env.d.ts",
    # Read-only legacy evidence, not Hub code; still scanned by gitleaks (Q-055, D-13).
    "context/legacy-source/**",
)


class GitError(RuntimeError):
    """git is missing, or the working directory is not inside a repository."""


def _git(args: Sequence[str], cwd: Path) -> bytes:
    try:
        completed = subprocess.run(  # noqa: S603 - fixed argv, no shell
            ["git", *args],  # noqa: S607 - git is resolved from PATH on purpose
            cwd=cwd,
            capture_output=True,
            check=False,
        )
    except FileNotFoundError as exc:
        raise GitError("git executable not found on PATH") from exc
    if completed.returncode != 0:
        detail = completed.stderr.decode("utf-8", errors="replace").strip()
        raise GitError(detail or f"git {args[0]} exited with {completed.returncode}")
    return completed.stdout


def repo_root(cwd: Path) -> Path:
    return Path(_git(["rev-parse", "--show-toplevel"], cwd).decode("utf-8").strip())


def tracked_files(cwd: Path, paths: Sequence[str] = ()) -> list[str]:
    """Repo-relative POSIX paths tracked by git, restricted to ``paths`` (cwd-relative) if given."""
    if paths:
        args = ["--literal-pathspecs", "ls-files", "-z", "--full-name", "--", *paths]
        output = _git(args, cwd)
    else:
        output = _git(["ls-files", "-z"], repo_root(cwd))
    return [entry.decode("utf-8") for entry in output.split(b"\0") if entry]


def is_checked(rel_path: str) -> bool:
    """True if ``rel_path`` is a code file that C-14 applies to."""
    if PurePosixPath(rel_path).suffix.lower() not in CODE_SUFFIXES:
        return False
    return not match_any(rel_path, EXCLUDED_GLOBS)


def count_lines(path: Path) -> int:
    """Physical lines ending in LF, CRLF or a lone CR; a last line without one still counts."""
    # bytes.splitlines() splits only on \n, \r\n and \r (not the extra Unicode separators).
    return len(path.read_bytes().splitlines())


def find_oversized(root: Path, rel_paths: Sequence[str]) -> tuple[int, list[tuple[str, int]]]:
    """Return (files checked, [(path, lines)] over the limit) in ``rel_paths`` order."""
    checked = 0
    oversized: list[tuple[str, int]] = []
    for rel_path in rel_paths:
        if not is_checked(rel_path):
            continue
        path = root / rel_path
        if not path.is_file():
            # Tracked but deleted (or a submodule): nothing to measure in the working tree.
            continue
        checked += 1
        lines = count_lines(path)
        if lines > MAX_LINES:
            oversized.append((rel_path, lines))
    return checked, oversized


def _configure_streams() -> None:
    """Never crash on a non-ASCII path when the console encoding cannot represent it."""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if callable(reconfigure):
            reconfigure(errors="backslashreplace")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=f"Fail if a tracked .py/.ts/.tsx/.jsx file exceeds {MAX_LINES} lines (C-14).",
    )
    parser.add_argument(
        "paths", nargs="*", help="limit the check to these paths (pre-commit passes staged files)"
    )
    args = parser.parse_args(argv)
    _configure_streams()

    cwd = Path.cwd()
    try:
        root = repo_root(cwd)
        rel_paths = tracked_files(cwd, args.paths)
    except GitError as exc:
        print(f"check_file_size: {exc}", file=sys.stderr)
        return 2

    checked, oversized = find_oversized(root, rel_paths)
    if oversized:
        for rel_path, lines in oversized:
            print(f"{rel_path}: {lines} lines (max {MAX_LINES})", file=sys.stderr)
        print(
            f"check_file_size: {len(oversized)} file(s) over {MAX_LINES} lines; "
            "split by layer/responsibility (C-14, context/08 sec. 1).",
            file=sys.stderr,
        )
        return 1
    print(f"check_file_size: {checked} code file(s) checked, all within {MAX_LINES} lines.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

